/**
 * 실측으로 못 박는 테스트. 여기 쌍들은 **실제 pending 후보의 불일치 43쌍**(2026-09-30 원격 DB 조회)에서 갈래마다
 * 하나씩 뽑은 것이다 — 합성 예제로는 `칠십리로214번길`(이름에 숫자) · `1층,2층`(쉼표 붙은 꼬리) 같은 실제 표기를
 * 떠올리지 못한다. 40쌍이 표기 차이(`same`), 1쌍이 다른 가게(`different`), 2쌍이 지번↔도로명(`unknown`)이었다.
 */

import { describe, expect, it } from 'vitest';
import { addressKey, sameAddress } from './addressMatch';

describe("sameAddress — 표기만 다른 것은 'same'", () => {
  it.each([
    // 실측 43쌍 중 39쌍이 이 한 갈래였다. 네이버는 `제주`, AI 는 본문 그대로 `제주특별자치도` 를 쓴다.
    ['제주 서귀포시 중문관광로 154-17', '제주특별자치도 서귀포시 중문관광로 154-17'],
    // 뒤에 붙은 상호 — 네이버 쪽에만 있기도 하고, AI 쪽에만 있기도 하다.
    ['제주 제주시 애월읍 애월해안로 179 본카페', '제주특별자치도 제주시 애월읍 애월해안로 179'],
    ['제주 제주시 한림읍 협재4길 19', '제주특별자치도 제주시 한림읍 협재4길 19 배롱정원'],
    ['제주 제주시 구좌읍 비자숲길 21 검은색 건물', '제주 제주시 구좌읍 비자숲길 21'],
    // 층·호 꼬리. 쉼표로 붙은 것도 본문 주소의 표준 표기다.
    ['제주 제주시 산지로 23', '제주특별자치도 제주시 산지로 23 1층'],
    ['제주 제주시 1100로 3198-20 1층 105호', '제주특별자치도 제주시 1100로 3198-20'],
    ['제주 서귀포시 칠십리로214번길 9 1층,2층', '제주특별자치도 서귀포시 칠십리로214번길 9'],
    ['제주 제주시 애월읍 애월해안로 899 1층(빨간머리앤), 2층, 3층', '제주 제주시 애월읍 애월해안로 899'],
    // 괄호 안 행정동 병기.
    ['제주 제주시 수목원길 16-14', '제주 제주시 수목원길 16-14 (노형동)'],
    // 시·도 접두어가 아예 없는 본문 주소 + 읍·면 생략.
    ['제주 제주시 한경면 한장서길 48-39 1층 덕봉이네', '제주시 한경면 한장서길 48-39'],
    ['제주 제주시 신설로2길 18-1 민하우스', '제주시 신설로2길 18-1'],
    // 시를 아예 뺀 본문 표기. 사슬을 앞에서부터 짝지으면 `애월읍` 이 상대의 `제주시` 자리에 서서 '다른 곳' 이 된다.
    ['제주 제주시 애월읍 애월해안로 179', '제주 애월읍 애월해안로 179'],
    // `서귀포` 는 '시' 가 떨어져 시 급이 비는 것으로 본다 — 비교하지 않는 급이다.
    ['제주 서귀포시 성산읍 난산로41번길 38', '서귀포 성산읍 난산로41번길 38'],
    // 도로명이 공백으로 갈린 표기. 붙이지 않으면 축이 `214번길` 이 돼 이름이 다르다고 읽힌다.
    ['제주 서귀포시 칠십리로214번길 9 1층,2층', '제주특별자치도 서귀포시 칠십리로 214번길 9'],
  ])('%s ↔ %s', (a, b) => {
    expect(sameAddress(a, b)).toBe('same');
    // 방향이 바뀌어도 같은 답이어야 한다 — 꼬리가 어느 쪽에 붙는지는 후보마다 다르다.
    expect(sameAddress(b, a)).toBe('same');
  });
});

describe("sameAddress — 진짜 다른 곳은 'different'", () => {
  /**
   * 값어치가 있는 유일한 갈래다. `naverLocal` 이 동명의 다른 가게를 집었다는 뜻이고, 그대로 승인하면
   * 엉뚱한 좌표·카테고리가 `places` 에 들어간다. 실측에서 이 쌍이 두 후보에 걸쳐 나왔다.
   */
  it('시가 갈리면 표기 문제가 아니다', () => {
    expect(sameAddress('제주 서귀포시 대포로 93', '제주특별자치도 제주시 애월읍 신엄안3길 95')).toBe('different');
  });

  it('읍·면이 갈려도 마찬가지 — 같은 시 안의 다른 동네다', () => {
    expect(sameAddress('제주 제주시 애월읍 봉성로 96-13', '제주 제주시 한림읍 봉성로 96-13')).toBe('different');
  });

  /** 생략은 넘기지만 **있는데 다른 것**은 넘기지 않는다 — 급별 비교가 그 둘을 가르는 전부다. */
  it('한쪽이 급을 생략한 것과, 양쪽에 있는데 값이 다른 것을 구별한다', () => {
    expect(sameAddress('제주 애월읍 봉성로 96-13', '제주 한림읍 봉성로 96-13')).toBe('different');
    expect(sameAddress('제주 봉성로 96-13', '제주 한림읍 봉성로 96-13')).toBe('same');
  });

  /** 번호 뒤가 그냥 숫자면 붙이지 않는다 — `번영로 2610` 의 2610 은 도로명의 일부가 아니라 건물번호다. */
  it("'로 + 숫자' 는 붙이지 않는다(붙이면 건물번호가 도로명에 먹힌다)", () => {
    expect(sameAddress('제주 서귀포시 표선면 번영로 2610 1층', '제주 서귀포시 표선면 번영로 2611')).toBe('different');
  });

  it('같은 도로의 다른 번호는 다른 건물이다', () => {
    expect(sameAddress('제주 제주시 한림읍 협재1길 22', '제주 제주시 한림읍 협재1길 24')).toBe('different');
  });

  it('번호의 부번까지 본다 — 18 과 18-2 는 다르다', () => {
    expect(sameAddress('제주 제주시 조천읍 함덕27길 18', '제주 제주시 조천읍 함덕27길 18-2')).toBe('different');
  });
});

describe("sameAddress — 비교할 수 없으면 'unknown'(경보가 아니다)", () => {
  /**
   * 지번↔도로명은 **조회해야** 같은 건물인지 아는 것이라 여기서 판단하지 않는다. AI 에게 물으면 지어내고,
   * 지어낸 '같다' 는 위 `different` 갈래를 덮어 버린다 — 하나 있는 진짜 신호를 잃는다.
   */
  it.each([
    ['제주 제주시 조천읍 함덕27길 18-2 1~2동 1층', '제주 제주시 조천읍 함덕리 272-4'],
    ['제주 서귀포시 표선면 민속해안로 1', '제주 서귀포시 표선면 세화리 283'],
  ])('지번 ↔ 도로명: %s ↔ %s', (a, b) => {
    expect(sameAddress(a, b)).toBe('unknown');
    expect(sameAddress(b, a)).toBe('unknown');
  });

  it.each([null, undefined, '', '   ', '제주 제주시 애월읍', '제주도'])('못 읽는 주소(%o)', (value) => {
    expect(sameAddress('제주 제주시 애월읍 애월해안로 179', value)).toBe('unknown');
  });
});

describe('addressKey — 무엇을 축으로 잡는가', () => {
  /** 번호 뒤의 `1~2동` 이 지번 이름으로 걸리면 안 된다 — 이름과 번호를 **짝으로** 찾는 이유다. */
  it('번호가 따라오는 첫 이름 토큰이 축이고, 그 뒤는 전부 버린다', () => {
    expect(addressKey('제주 제주시 조천읍 함덕27길 18-2 1~2동 1층')).toEqual({
      city: '제주시',
      town: '조천읍',
      base: '함덕27길',
      number: '18-2',
      kind: 'road',
    });
  });

  /** 도로명에 숫자가 박힌 것은 제주에 흔하다(`1100로`) — 번호 토큰을 이름 안의 숫자로 착각하면 안 된다. */
  it('이름 안의 숫자를 번호로 읽지 않는다', () => {
    expect(addressKey('제주특별자치도 제주시 1100로 3198-20 1층 105호')).toMatchObject({
      base: '1100로',
      number: '3198-20',
    });
  });

  it('시내(동 단위) 주소는 읍·면이 없다 — 그 급은 비교에서 빠진다', () => {
    expect(addressKey('제주특별자치도 제주시 도령로 100')).toEqual({
      city: '제주시',
      town: null,
      base: '도령로',
      number: '100',
      kind: 'road',
    });
  });

  it('지번주소는 kind 가 갈린다', () => {
    expect(addressKey('제주 서귀포시 표선면 세화리 283')).toMatchObject({ base: '세화리', number: '283', kind: 'lot' });
  });
});
