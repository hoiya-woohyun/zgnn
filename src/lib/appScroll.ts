import { normalizeRoute } from "./appRoutes";

/**
 * 화면마다 "어디까지 내려 봤는지" 를 기억한다. **예외 없이 모든 화면이** 자기 자리를 지킨다.
 *
 * 두 가지 이동이 같은 답을 요구한다.
 *
 * 하나는 좌우 스와이프다. 손가락으로 밀어 넘기면 사용자는 다섯 화면이 **나란히 떠 있다**고
 * 느낀다. 나란히 떠 있는 것은 눈을 뗐다고 맨 위로 되감기지 않는다 — 준비물을 한참 내려 보다
 * 설정을 잠깐 들렀다 돌아왔는데 다시 맨 위면, 옆으로 민 것이 아니라 새로 연 것이 된다.
 *
 * 다른 하나는 목록 → 상세 → 뒤로다. 저장한 곳을 한참 내려 보다 한 곳을 열고 되돌아 나왔으면
 * **보고 있던 그 항목**이 다시 보여야 한다. 목록의 맨 위로 돌아가면 방금 무엇을 봤는지 찾는
 * 일을 처음부터 다시 하게 된다.
 *
 * **예외를 두지 않는 것이 이 파일의 요점이다.** 전에는 탭바 화면만 제자리를 지키고 하위 화면은
 * 늘 맨 위였는데, 그 가름의 근거("옆에 나란히 떠 있던 것이 아니라 방금 연 것이다")는 주소로
 * 확인할 수 없는 말이다 — 같은 `/place/:id` 에 처음 들어가는 것과 뒤로가기로 되돌아오는 것이
 * 주소로는 구별되지 않는다. 주소만 보고 가르려 하면 반드시 한쪽이 틀리고, 틀린 쪽은
 * `/saved` 였다(루트가 아니라, 목록을 한참 내려 보고 상세를 들렀다 나오면 맨 위로 되감겼다).
 *
 * 그래서 여기서는 **기억한 자리를 그대로 준다**. 맨 위에서 시작해야 하는 이동이 있으면
 * **그 이동을 하는 쪽**이 도착점 기억을 0 으로 적어 말한다 — 둘러보기의 종류 전환이 그렇게
 * 한다(`screens/placesPageSwipe.ts` 의 `settle`). 거기는 엿보기가 이웃을 맨 위로 그리기로 되어
 * 있어서([ADR-013](../../docs/decisions/ADR-013-places-swipe-pager.md)) 옛 자리로 앉히면 손가락을
 * 놓는 순간 목록이 튄다. **그 한 줄이 스와이프로 종류를 바꾸는 경로를 떠받친다** — 지우면 빌드와
 * 테스트는 그대로 통과하고 그 경로만 조용히 어긋난다.
 *
 * ## 탭으로 옮기면 복원되지 않는다 (실측, 원인 미확인)
 *
 * 여기 적어 둔 자리가 실제로 쓰이는 이동은 **스와이프(`scroll: false`)와 뒤로/앞으로(popstate)**
 * 다. 탭바·사이드바·둘러보기 알약처럼 `next/link` 를 그냥 탭해서 옮기면 도착은 늘 맨 위였다 —
 * 준비물을 243px 내려 보고 설정에 갔다가 탭으로 되돌아오면 0 이다(2026-09-18 실측, dev).
 * 탭바 화면만 복원하던 옛 정책에서도 탭 경로는 마찬가지였다. 그래서 알약으로 종류를 바꾸는
 * 경로는 위의 `settle` 이 아니라 이쪽이 맨 위로 보내고 있다.
 *
 * **원인은 확인하지 못했다.** Next 의 기본 스크롤(`ScrollBehavior.Default`)이 유력하지만
 * 타임라인을 재지 못했으니 추정으로 둔다. 탭도 스와이프와 같게 만들려면 그 `<Link>` 들에
 * `scroll: false` 를 주는 것이 먼저 해 볼 일이다(아직 안 했다).
 *
 * **모듈 변수인 것도 요점이다.** 화면은 주소가 바뀔 때마다 통째로 새로 마운트되므로
 * (둘러보기는 `key={type}` 로 한 번 더) 어떤 컴포넌트 상태에도 남지 않는다. 마운트를 넘어
 * 살아남는 자리가 여기뿐이다. 새로고침하면 비는 것도 맞다 — 그때는 정말 새로 연 것이다.
 */
const offsets = new Map<string, number>();

/** 지금 보고 있는 화면의 세로 위치를 적어 둔다. 화면을 떠나기 전에 불려야 뜻이 있다. */
export const rememberScroll = (pathname: string, offset: number): void => {
  offsets.set(normalizeRoute(pathname), Math.max(0, offset));
};

/**
 * 그 화면에 도착했을 때 놓일 세로 위치. 기억이 없으면(처음 가는 화면) 0 이다.
 *
 * 주소로 화면을 가리지 않는다 — 위의 "예외를 두지 않는 것이 요점" 을 볼 것.
 */
export const arrivalScrollOf = (pathname: string): number =>
  offsets.get(normalizeRoute(pathname)) ?? 0;

/** 기억을 지운다. 테스트가 서로의 자리를 물려받지 않게 하는 용도. */
export const forgetScrollMemory = (): void => {
  offsets.clear();
};
